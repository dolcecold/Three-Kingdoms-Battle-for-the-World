import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {dirname} from 'node:path';
import {familyName,mentionsOfDeck,matchupTargets,countersForTarget} from '../matchup-explorer.js';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const read=f=>JSON.parse(readFileSync(join(root,f),'utf8'));
const variants=read('references/data/kr_s3_deck_references.json').variants;
const items=read('data/recommendation-matchups.json').items;
const demon=variants.find(v=>v.label==='악마제갈 · 세팅 1');
assert.ok(demon);
assert.equal(items[demon.id],undefined,'악마제갈에 직접 상성이 있다고 주장하면 안 됨');
const inbound=mentionsOfDeck(demon,variants,items);
assert.ok(inbound.some(x=>familyName(x.variant)==='준숭술'&&x.relation==='caution'));
assert.ok(!inbound.some(x=>x.relation==='good'), '주의 메모를 확정 승리로 변환 금지');
const targets=matchupTargets(items);
assert.ok(targets.some(x=>x.target==='추격형 속공덱'));
const counters=countersForTarget('추격형 속공덱',variants,items);
assert.ok(counters.some(x=>x.variant.label.startsWith('호위')));
assert.ok(counters.some(x=>x.variant.label.startsWith('준숭술')));
assert.equal(countersForTarget('악마제갈',variants,items).length,0,'직접 good 없으면 결과 없음');
assert.equal(countersForTarget('알 수 없는 덱',variants,items).length,0);
console.log('matchup-explorer tests: OK; inbound 악마제갈:',inbound.length,'/ 카운터 추격형 속공덱:',counters.length,'/ 대상 유형:',targets.length);
